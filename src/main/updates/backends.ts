import { app, net } from 'electron'
import { existsSync, readFileSync } from 'node:fs'
import { join } from 'node:path'
import { InvalidReleaseError, releaseToUpdate, type AvailableUpdate, type PackageFormat } from '@shared/updates'
import type { UpdateBackend } from './updateService'
import { tl } from '@shared/i18n'

/**
 * How this copy of Azm was installed. electron-builder writes a
 * `package-type` file into DEB and RPM packages; AppImages set $APPIMAGE.
 */
export function detectPackageFormat(): PackageFormat {
  if (!app.isPackaged) return 'dev'
  if (process.platform === 'win32') return 'nsis'
  if (process.platform !== 'linux') return 'other'
  if (process.env.APPIMAGE) return 'appimage'
  try {
    const type = readFileSync(join(process.resourcesPath, 'package-type'), 'utf8').trim()
    if (type === 'deb' || type === 'rpm') return type
  } catch {
    /* fall through */
  }
  if (existsSync('/var/lib/dpkg/info/focusflow.list')) return 'deb'
  return 'other'
}

type Fetcher = (url: string, init: { headers: Record<string, string>; signal: AbortSignal }) => Promise<Response>

/**
 * "Notify and link" updates: asks the GitHub API for the latest *stable*
 * release (drafts and prereleases are excluded by GitHub) and validates it.
 * Used for DEB, RPM and AppImage, where the system package manager (or the
 * user) installs the new version. It never downloads or runs anything.
 */
export class GitHubReleaseBackend implements UpdateBackend {
  readonly mode = 'manual' as const

  constructor(
    private readonly repository: string,
    readonly format: PackageFormat,
    private readonly currentVersion: string,
    private readonly fetcher: Fetcher = (url, init) => net.fetch(url, init)
  ) {}

  async check(): Promise<AvailableUpdate | null> {
    const res = await this.fetcher(`https://api.github.com/repos/${this.repository}/releases/latest`, {
      headers: { Accept: 'application/vnd.github+json', 'User-Agent': 'Azm-update-check' },
      signal: AbortSignal.timeout(15_000)
    })
    if (res.status === 404) return null // no stable release published yet
    if (res.status === 403 || res.status === 429) {
      throw new InvalidReleaseError(tl('update.err.rateLimited'))
    }
    if (!res.ok) throw new InvalidReleaseError(`GitHub answered with status ${res.status}. Try again later.`)
    let body: unknown
    try {
      body = await res.json()
    } catch {
      throw new InvalidReleaseError(tl('update.err.unreadable'))
    }
    return releaseToUpdate(body, this.repository, this.currentVersion, this.format)
  }
}

/**
 * In-app updates for the Windows NSIS installer, via electron-updater. It
 * reads the feed from app-update.yml (generated by electron-builder from
 * package.json "repository"), downloads the installer named in the
 * release's latest.yml and verifies its SHA-512 before it can run.
 * Nothing downloads or installs without an explicit user action.
 */
export async function createNsisBackend(repository: string): Promise<UpdateBackend> {
  const { NsisUpdater } = await import('electron-updater')
  const updater = new NsisUpdater()
  updater.autoDownload = false
  updater.autoInstallOnAppQuit = false
  updater.allowPrerelease = false
  updater.allowDowngrade = false
  updater.logger = {
    info: () => {},
    debug: () => {},
    warn: (m: unknown) => console.warn('[updates]', m),
    error: (m: unknown) => console.error('[updates]', m)
  }

  return {
    mode: 'install',
    format: 'nsis',
    async check() {
      const result = await updater.checkForUpdates()
      if (!result || !result.isUpdateAvailable) return null
      const version = result.updateInfo.version
      return {
        version,
        releaseUrl: `https://github.com/${repository}/releases/tag/v${version}`,
        assetUrl: null,
        assetName: null,
        installCommand: null
      }
    },
    async download(onProgress) {
      const listener = (p: { percent: number; transferred: number; total: number }): void => onProgress(p)
      updater.on('download-progress', listener)
      try {
        await updater.downloadUpdate()
      } finally {
        updater.off('download-progress', listener)
      }
    },
    install() {
      // Not silent: the user sees the installer. Relaunch Azm afterwards.
      updater.quitAndInstall(false, true)
    },
    setInstallOnQuit(enabled) {
      updater.autoInstallOnAppQuit = enabled
    }
  }
}
